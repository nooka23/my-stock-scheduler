-- US/global market-data foundation for the pre-market morning briefing.
--
-- Design rules:
--   * Keep this separate from public.daily_prices_v2, which feeds the Korean
--     stock universe, RS rankings, and existing daily jobs.
--   * ETL writes with the Supabase service role; dashboard clients receive
--     read-only access through explicit grants/RLS.
--   * Provider identifiers are configuration, not facts. Do not guess KIS
--     instrument codes for indices, rates, FX, or futures.

create schema if not exists market_data;

create or replace function market_data.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists market_data.market_instruments (
  id uuid primary key default gen_random_uuid(),
  internal_code text not null unique,
  display_name text not null,
  asset_class text not null check (
    asset_class in ('INDEX', 'EQUITY', 'RATE', 'FX', 'COMMODITY', 'FUTURE')
  ),
  country text,
  exchange text,
  currency text not null default 'USD',
  provider text not null,
  provider_symbol text,
  provider_params jsonb not null default '{}'::jsonb,
  display_order integer not null default 1000,
  is_enabled boolean not null default false,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint market_instruments_provider_symbol_key
    unique (provider, provider_symbol)
    deferrable initially immediate
);

comment on table market_data.market_instruments is
  'Canonical instrument registry for US/global morning-brief data. Provider codes are configured here, not hard-coded in collectors.';
comment on column market_data.market_instruments.provider_params is
  'Provider-specific request parameters such as exchange/market code. Never store credentials.';

drop trigger if exists market_instruments_set_updated_at
  on market_data.market_instruments;
create trigger market_instruments_set_updated_at
before update on market_data.market_instruments
for each row execute function market_data.set_updated_at();

create index if not exists market_instruments_enabled_order_idx
  on market_data.market_instruments (is_enabled, display_order, asset_class);

create table if not exists market_data.global_daily_prices (
  id bigint generated by default as identity primary key,
  instrument_id uuid not null references market_data.market_instruments(id) on delete cascade,
  trade_date date not null,
  open numeric,
  high numeric,
  low numeric,
  close numeric,
  volume numeric,
  trading_value numeric,
  currency text not null,
  source text not null,
  source_updated_at timestamptz,
  fetched_at timestamptz not null default now(),
  raw_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (instrument_id, trade_date, source),
  check (open is null or open >= 0),
  check (high is null or high >= 0),
  check (low is null or low >= 0),
  check (close is null or close >= 0),
  check (volume is null or volume >= 0),
  check (trading_value is null or trading_value >= 0)
);

comment on table market_data.global_daily_prices is
  'Normalized daily OHLCV for US/global instruments. Values remain in the instrument currency.';

drop trigger if exists global_daily_prices_set_updated_at
  on market_data.global_daily_prices;
create trigger global_daily_prices_set_updated_at
before update on market_data.global_daily_prices
for each row execute function market_data.set_updated_at();

create index if not exists global_daily_prices_date_idx
  on market_data.global_daily_prices (trade_date desc, instrument_id);
create index if not exists global_daily_prices_instrument_date_idx
  on market_data.global_daily_prices (instrument_id, trade_date desc);

create table if not exists market_data.market_snapshots (
  id bigint generated by default as identity primary key,
  instrument_id uuid not null references market_data.market_instruments(id) on delete cascade,
  observed_at timestamptz not null,
  price numeric not null,
  change_value numeric,
  change_pct numeric,
  session text not null default 'PREMARKET',
  source text not null,
  is_delayed boolean not null default false,
  source_updated_at timestamptz,
  fetched_at timestamptz not null default now(),
  raw_payload jsonb not null default '{}'::jsonb,
  unique (instrument_id, observed_at, source)
);

comment on table market_data.market_snapshots is
  'Point-in-time quotes used for the 08:05 KST pre-open tape and later intraday refreshes.';

create index if not exists market_snapshots_instrument_observed_idx
  on market_data.market_snapshots (instrument_id, observed_at desc);
create index if not exists market_snapshots_observed_idx
  on market_data.market_snapshots (observed_at desc, source);

create table if not exists market_data.data_ingestion_runs (
  id uuid primary key default gen_random_uuid(),
  pipeline_key text not null,
  source text not null,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  status text not null default 'RUNNING' check (
    status in ('RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED')
  ),
  rows_read integer not null default 0,
  rows_written integer not null default 0,
  error_message text,
  metadata jsonb not null default '{}'::jsonb
);

comment on table market_data.data_ingestion_runs is
  'Operational audit trail for idempotent market-data collectors and freshness checks.';

create index if not exists data_ingestion_runs_pipeline_started_idx
  on market_data.data_ingestion_runs (pipeline_key, started_at desc);

