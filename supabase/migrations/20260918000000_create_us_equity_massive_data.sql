-- Dedicated US common-stock universe and daily OHLCV storage.
-- This is intentionally separate from public.companies/daily_prices_v2.

create schema if not exists market_data;

create table if not exists market_data.us_equity_universe (
  ticker text primary key,
  company_name text not null,
  primary_exchange text not null,
  security_type text not null default 'CS',
  is_etf boolean not null default false,
  provider text not null default 'MASSIVE',
  provider_symbol text not null,
  is_active boolean not null default true,
  first_seen_on date not null default current_date,
  last_seen_on date,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (security_type = 'CS'),
  check (is_etf = false)
);

comment on table market_data.us_equity_universe is
  'Active US-listed common stocks from Massive. ETFs and other security types are excluded at ingestion.';

create index if not exists us_equity_universe_active_exchange_idx
  on market_data.us_equity_universe (is_active, primary_exchange, ticker);

create table if not exists market_data.us_daily_prices (
  id bigint generated by default as identity primary key,
  ticker text not null references market_data.us_equity_universe(ticker),
  trade_date date not null,
  open numeric,
  high numeric,
  low numeric,
  close numeric,
  volume numeric,
  trading_value numeric,
  vwap numeric,
  change numeric,
  change_pct numeric,
  market_cap numeric,
  currency text not null default 'USD',
  source text not null,
  source_updated_at timestamptz,
  fetched_at timestamptz not null default now(),
  raw_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (ticker, trade_date, source),
  check (open is null or open >= 0),
  check (high is null or high >= 0),
  check (low is null or low >= 0),
  check (close is null or close >= 0),
  check (volume is null or volume >= 0),
  check (trading_value is null or trading_value >= 0),
  check (vwap is null or vwap >= 0),
  check (market_cap is null or market_cap >= 0)
);

comment on table market_data.us_daily_prices is
  'Daily OHLCV for the dedicated US common-stock universe. trading_value is an estimate of close multiplied by volume; market_cap is reserved for a future reference-data enrichment job.';

create index if not exists us_daily_prices_ticker_date_idx
  on market_data.us_daily_prices (ticker, trade_date desc);
create index if not exists us_daily_prices_date_idx
  on market_data.us_daily_prices (trade_date desc, ticker);

drop trigger if exists us_equity_universe_set_updated_at
  on market_data.us_equity_universe;
create trigger us_equity_universe_set_updated_at
before update on market_data.us_equity_universe
for each row execute function market_data.set_updated_at();

drop trigger if exists us_daily_prices_set_updated_at
  on market_data.us_daily_prices;
create trigger us_daily_prices_set_updated_at
before update on market_data.us_daily_prices
for each row execute function market_data.set_updated_at();

grant all on market_data.us_equity_universe to service_role;
grant all on market_data.us_daily_prices to service_role;
grant usage, select on sequence market_data.us_daily_prices_id_seq to service_role;

alter table market_data.us_equity_universe enable row level security;
alter table market_data.us_daily_prices enable row level security;

-- No public read policy is created here. The collector uses service_role;
-- expose data to application users only through a separately reviewed view or
-- API boundary when a US-stock UI is requested.
