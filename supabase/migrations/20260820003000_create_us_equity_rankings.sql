-- US equity ranking snapshots used by the shared morning briefing.
-- Keep ranking facts separate from the 13-instrument daily-price universe:
-- KIS ranking endpoints can return a much broader and changing universe.

create table if not exists market_data.us_equity_rankings (
  id bigint generated by default as identity primary key,
  run_id uuid not null references market_data.data_ingestion_runs(id) on delete cascade,
  brief_date date not null,
  session text not null default 'US_CLOSE',
  observed_at timestamptz not null,
  ranking_type text not null check (
    ranking_type in (
      'MARKET_CAP',
      'UPDOWN_GAINER',
      'UPDOWN_LOSER',
      'TRADE_VOLUME',
      'TRADE_VALUE'
    )
  ),
  exchange text not null,
  rank integer not null check (rank > 0),
  symbol text not null,
  display_name text,
  price numeric,
  change_value numeric,
  change_pct numeric,
  volume numeric,
  trading_value numeric,
  average_volume numeric,
  average_trading_value numeric,
  shares_outstanding numeric,
  market_cap_raw numeric,
  market_cap_unit text,
  currency text not null default 'USD',
  source text not null,
  fetched_at timestamptz not null default now(),
  raw_payload jsonb not null default '{}'::jsonb,
  unique (brief_date, session, ranking_type, exchange, rank, source),
  check (price is null or price >= 0),
  check (volume is null or volume >= 0),
  check (trading_value is null or trading_value >= 0),
  check (average_volume is null or average_volume >= 0),
  check (average_trading_value is null or average_trading_value >= 0),
  check (shares_outstanding is null or shares_outstanding >= 0),
  check (market_cap_raw is null or market_cap_raw >= 0)
);

comment on table market_data.us_equity_rankings is
  'KIS overseas-stock ranking snapshots for the office morning briefing. A rerun for the same brief date/session replaces rows and points them to the latest ingestion run.';
comment on column market_data.us_equity_rankings.market_cap_raw is
  'KIS market-cap field as returned. Do not label or convert it until KIS unit semantics are independently verified.';

create index if not exists us_equity_rankings_run_idx
  on market_data.us_equity_rankings (run_id, ranking_type, exchange, rank);
create index if not exists us_equity_rankings_brief_idx
  on market_data.us_equity_rankings (brief_date desc, session, ranking_type, exchange, rank);
create index if not exists us_equity_rankings_symbol_idx
  on market_data.us_equity_rankings (symbol, brief_date desc);

alter table market_data.us_equity_rankings enable row level security;

drop policy if exists us_equity_rankings_public_read
  on market_data.us_equity_rankings;
create policy us_equity_rankings_public_read
  on market_data.us_equity_rankings for select
  to anon, authenticated using (true);

grant select on market_data.us_equity_rankings to anon, authenticated;
grant all on market_data.us_equity_rankings to service_role;
grant usage, select on sequence market_data.us_equity_rankings_id_seq to service_role;

-- Never fall back to a preceding successful run when the latest attempt fails.
-- The absence of rows is intentional: the presentation layer must show 미갱신.
create or replace view market_data.v_us_top_market_cap
with (security_invoker = true) as
with latest_attempt as (
  select id, status, started_at, completed_at
  from market_data.data_ingestion_runs
  where pipeline_key = 'us_equity_rankings'
    and source = 'KIS_OVERSEAS_RANKING'
  order by started_at desc
  limit 1
)
select
  r.brief_date,
  r.session,
  r.observed_at,
  r.exchange,
  r.rank,
  r.symbol,
  r.display_name,
  r.price,
  r.change_value,
  r.change_pct,
  r.volume,
  r.trading_value,
  r.shares_outstanding,
  r.market_cap_raw,
  r.market_cap_unit,
  r.currency,
  r.source,
  a.status as run_status,
  a.started_at as run_started_at,
  a.completed_at as run_completed_at,
  case when a.status = 'SUCCEEDED' then 'fresh' else 'partial' end as quality_status
from latest_attempt a
join market_data.us_equity_rankings r on r.run_id = a.id
where a.status in ('SUCCEEDED', 'PARTIAL')
  and r.ranking_type = 'MARKET_CAP'
  and r.rank <= 20
order by r.exchange, r.rank;

comment on view market_data.v_us_top_market_cap is
  'Top 20 KIS market-cap ranks per US exchange from the latest successful or partial attempt. Market-cap values remain raw until source-unit validation is complete.';

create or replace view market_data.v_us_featured_candidates
with (security_invoker = true) as
with latest_attempt as (
  select id, status, started_at, completed_at
  from market_data.data_ingestion_runs
  where pipeline_key = 'us_equity_rankings'
    and source = 'KIS_OVERSEAS_RANKING'
  order by started_at desc
  limit 1
), current_rankings as (
  select r.*, a.status, a.started_at, a.completed_at
  from latest_attempt a
  join market_data.us_equity_rankings r on r.run_id = a.id
  where a.status in ('SUCCEEDED', 'PARTIAL')
    and r.ranking_type in (
      'UPDOWN_GAINER', 'UPDOWN_LOSER', 'TRADE_VOLUME', 'TRADE_VALUE'
    )
    and r.rank <= 20
)
select
  brief_date,
  session,
  observed_at,
  exchange,
  symbol,
  max(display_name) as display_name,
  array_agg(ranking_type order by ranking_type, rank) as candidate_signals,
  jsonb_agg(
    jsonb_build_object(
      'ranking_type', ranking_type,
      'rank', rank,
      'price', price,
      'change_value', change_value,
      'change_pct', change_pct,
      'volume', volume,
      'trading_value', trading_value,
      'average_volume', average_volume,
      'average_trading_value', average_trading_value,
      'currency', currency,
      'source', source
    ) order by ranking_type, rank
  ) as signal_details,
  max(status) as run_status,
  max(started_at) as run_started_at,
  max(completed_at) as run_completed_at,
  case when max(status) = 'SUCCEEDED' then 'fresh' else 'partial' end as quality_status
from current_rankings
group by brief_date, session, observed_at, exchange, symbol;

comment on view market_data.v_us_featured_candidates is
  'Source-ranked US featured-stock candidates. This is a transparent union of top-20 gainers, losers, volume ranks, and value ranks; it is not a trading recommendation.';

grant select on market_data.v_us_top_market_cap, market_data.v_us_featured_candidates
  to anon, authenticated, service_role;
